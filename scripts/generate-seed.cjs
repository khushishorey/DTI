// Generates supabase/seed.sql: demo players around the mock map centre, each owning a
// cluster of H3 res-10 cells. Run: node scripts/generate-seed.cjs
// Local development only — the demo password is not a secret.
const fs = require('fs');
const path = require('path');
const { latLngToCell, gridDisk, cellToLatLng } = require('h3-js');

const CENTER = { lat: 37.78825, lng: -122.4324 }; // matches src/data/mockRunRoute.ts
const RES = 10;
const DEMO_PASSWORD = 'runio-demo-123';

const players = [
  { id: '00000000-0000-4000-8000-000000000001', username: 'GhostStride', color: '#5BC0EB', dLat: 0.004, dLng: 0.003, ring: 2, xp: 22150 },
  { id: '00000000-0000-4000-8000-000000000002', username: 'NovaPace', color: '#FF8C42', dLat: -0.003, dLng: -0.002, ring: 2, xp: 19380 },
  { id: '00000000-0000-4000-8000-000000000003', username: 'MossRunner', color: '#B084F5', dLat: -0.004, dLng: 0.004, ring: 1, xp: 16840 },
  { id: '00000000-0000-4000-8000-000000000004', username: 'Northstar', color: '#FF5BA7', dLat: 0.006, dLng: -0.004, ring: 1, xp: 20510 },
];

const sql = [];
sql.push('-- Generated by scripts/generate-seed.cjs — do not edit by hand.');
sql.push(`-- Demo accounts (local only): <username>@demo.run.io / ${DEMO_PASSWORD}`);
sql.push('');
for (const p of players) {
  const email = `${p.username.toLowerCase()}@demo.run.io`;
  sql.push(`insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, recovery_token, email_change, email_change_token_new)
values ('00000000-0000-0000-0000-000000000000', '${p.id}', 'authenticated', 'authenticated', '${email}', extensions.crypt('${DEMO_PASSWORD}', extensions.gen_salt('bf')), now(), '{"provider":"email","providers":["email"]}', '{"username":"${p.username}","color":"${p.color}"}', now(), now(), '', '', '', '');`);
  sql.push(`insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
values (gen_random_uuid(), '${p.id}', '${p.id}', '{"sub":"${p.id}","email":"${email}"}', 'email', now(), now(), now());`);
  sql.push(`update public.profiles set xp = ${p.xp} where id = '${p.id}';`);
}
sql.push('');

const taken = new Set();
for (const p of players) {
  const centre = latLngToCell(CENTER.lat + p.dLat, CENTER.lng + p.dLng, RES);
  const cells = gridDisk(centre, p.ring).filter((c) => !taken.has(c));
  cells.forEach((c) => taken.add(c));
  sql.push(`-- ${p.username}: ${cells.length} cells`);
  sql.push(
    `insert into public.cells (h3, owner_id, captured_at, center_lat, center_lng) values\n` +
      cells
        .map((c, i) => {
          const [lat, lng] = cellToLatLng(c);
          return `  ('${c}', '${p.id}', now() - interval '${i + 1} hours', ${lat.toFixed(7)}, ${lng.toFixed(7)})`;
        })
        .join(',\n') +
      ';',
  );
}

fs.writeFileSync(path.join(__dirname, '..', 'supabase', 'seed.sql'), sql.join('\n') + '\n');
console.log(`wrote seed.sql: ${players.length} players, ${taken.size} cells`);
